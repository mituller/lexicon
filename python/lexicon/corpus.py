"""Corpus generation: CEFR word lists -> Bedrock-enriched vocabulary records.

Pipeline (prompt.md Q-n):

    CEFR-J Vocabulary Profile (A1-B2) + Octanove (C1/C2)
        -> curated headword list (deterministic, deduped)
        -> Bedrock generates definition / example / synonyms
        -> JSONL in the schema from data/schema.md

The CEFR levels and topics come from the datasets; only the prose is generated. Attribution:
CEFR-J Vocabulary Profile, compiled by Yukio Tono, Tokyo University of Foreign Studies
(© Tono Lab, TUFS), free for research and commercial use with citation. The Octanove C1/C2
profile is CC BY-SA 4.0.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import re
from collections.abc import Callable, Iterable, Sequence
from dataclasses import dataclass, field

from .bedrock import BedrockClient
from .models import CEFR_TO_TIER, CefrLevel

# --- dataset parsing -------------------------------------------------------

_HEADWORD_KEYS = ("headword", "word", "lemma")
_POS_KEYS = ("pos", "part of speech", "partofspeech", "pos_tag")
_CEFR_KEYS = ("cefr", "cefr_level", "cefrlevel", "level")
_TOPIC_KEYS = ("coreinventory 1", "core inventory 1", "coreinventory1", "topic", "category")


@dataclass(frozen=True)
class CefrEntry:
    """A single headword from a CEFR word list."""

    headword: str
    pos: str
    cefr_level: str
    topic: str = ""


def _lookup(row: dict[str, str], keys: Sequence[str]) -> str:
    lowered = {k.strip().lower(): (v or "") for k, v in row.items()}
    for key in keys:
        if key in lowered and lowered[key].strip():
            return lowered[key].strip()
    return ""


def parse_cefr_csv(text: str) -> list[CefrEntry]:
    """Parse a CEFR-J / Octanove CSV into entries (column names are matched loosely)."""
    reader = csv.DictReader(io.StringIO(text))
    entries: list[CefrEntry] = []
    for row in reader:
        headword = _lookup(row, _HEADWORD_KEYS)
        cefr = _lookup(row, _CEFR_KEYS).upper()
        if not headword or not cefr:
            continue
        cefr = cefr.replace("PRE-A1", "Pre-A1").replace("PREA1", "Pre-A1")
        try:
            CefrLevel(cefr)
        except ValueError:
            continue  # skip unknown/annotated levels rather than guessing
        entries.append(
            CefrEntry(
                headword=headword,
                pos=_lookup(row, _POS_KEYS).lower(),
                cefr_level=cefr,
                topic=_lookup(row, _TOPIC_KEYS),
            )
        )
    return entries


def dedupe(entries: Iterable[CefrEntry]) -> list[CefrEntry]:
    """Keep the first entry per ``(headword, pos)`` case-insensitively."""
    seen: set[tuple[str, str]] = set()
    out: list[CefrEntry] = []
    for entry in entries:
        key = (entry.headword.lower(), entry.pos.lower())
        if key not in seen:
            seen.add(key)
            out.append(entry)
    return out


def curate(entries: Iterable[CefrEntry], *, limit_per_level: int | None = None) -> list[CefrEntry]:
    """Dedupe and cap the number of entries per CEFR level."""
    counts: dict[str, int] = {}
    out: list[CefrEntry] = []
    for entry in dedupe(entries):
        if limit_per_level is not None and counts.get(entry.cefr_level, 0) >= limit_per_level:
            continue
        counts[entry.cefr_level] = counts.get(entry.cefr_level, 0) + 1
        out.append(entry)
    return out


# --- Bedrock enrichment ----------------------------------------------------


@dataclass
class TermDetails:
    """Prose generated by Bedrock for a headword."""

    definition: str
    example: str = ""
    synonyms: list[str] = field(default_factory=list)


DETAILS_SYSTEM_PROMPT = (
    "You write concise dictionary entries for an English vocabulary tutor. "
    "Always reply with a single JSON object and nothing else."
)


def details_prompt(entry: CefrEntry) -> str:
    """Prompt asking Bedrock for a strict-JSON entry."""
    pos = f" Part of speech: {entry.pos}." if entry.pos else ""
    return (
        f"Write a learner dictionary entry for the English word \"{entry.headword}\" at CEFR "
        f"level {entry.cefr_level}.{pos}\n\n"
        "Return JSON with exactly these keys:\n"
        '  "definition": one clear sentence in plain English suitable for the level,\n'
        '  "example": one natural usage sentence,\n'
        '  "synonyms": array of up to 3 single-word synonyms (may be empty).\n'
        "Do not add any other keys or text."
    )


def parse_details(raw: str) -> TermDetails:
    """Parse Bedrock's JSON reply, tolerating code fences and surrounding prose."""
    text = raw.strip()
    fence = re.search(r"```(?:json)?\s*(.*?)```", text, flags=re.DOTALL)
    if fence:
        text = fence.group(1).strip()
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end == -1:
        raise ValueError(f"no JSON object in model reply: {raw[:200]!r}")
    payload = json.loads(text[start : end + 1])
    synonyms = payload.get("synonyms") or []
    if isinstance(synonyms, str):
        synonyms = [s.strip() for s in synonyms.split(",") if s.strip()]
    return TermDetails(
        definition=str(payload.get("definition", "")).strip(),
        example=str(payload.get("example", "")).strip(),
        synonyms=[str(s).strip() for s in synonyms if str(s).strip()][:3],
    )


def generate_details(entry: CefrEntry, bedrock: BedrockClient | None = None) -> TermDetails:
    """Call Bedrock to generate the definition/example/synonyms for one headword."""
    client = bedrock or BedrockClient()
    reply = client.generate(details_prompt(entry), system=DETAILS_SYSTEM_PROMPT)
    return parse_details(reply)


# --- record building -------------------------------------------------------

_SLUG_RE = re.compile(r"[^a-z0-9]+")


def slugify(value: str) -> str:
    return _SLUG_RE.sub("_", value.lower()).strip("_")


def make_term_id(entry: CefrEntry, *, prefix: str) -> str:
    """Deterministic, collision-resistant id, e.g. ``gen_abandon_verb_3f9c``."""
    base = f"{prefix}_{slugify(entry.headword)}"
    if entry.pos:
        base = f"{base}_{slugify(entry.pos)}"
    digest = hashlib.sha1(f"{entry.headword}|{entry.pos}|{entry.cefr_level}".encode()).hexdigest()
    return f"{base}_{digest[:4]}"


def build_record(
    entry: CefrEntry,
    details: TermDetails,
    *,
    domain: str = "general",
    id_prefix: str | None = None,
    source: str = "cefr-j",
) -> dict[str, object]:
    """Assemble a schema-conformant vocabulary record (see data/schema.md)."""
    cefr = CefrLevel(entry.cefr_level)
    prefix = id_prefix or ("gen" if domain == "general" else domain)
    return {
        "term_id": make_term_id(entry, prefix=prefix),
        "term": entry.headword,
        "definition": details.definition,
        "example": details.example,
        "synonyms": details.synonyms,
        "domain": domain,
        "subfield": slugify(entry.topic) if entry.topic else "linguistics",
        "cefr_level": cefr.value,
        "difficulty_tier": CEFR_TO_TIER[cefr].value,
        "pos": entry.pos,
        "source": source,
    }


def build_corpus(
    entries: Iterable[CefrEntry],
    generate: Callable[[CefrEntry], TermDetails],
    *,
    domain: str = "general",
    source: str = "cefr-j",
    limit_per_level: int | None = None,
    on_progress: Callable[[int, int], None] | None = None,
) -> list[dict[str, object]]:
    """Enrich curated entries into records. ``generate`` is injected so this is testable."""
    selected = curate(entries, limit_per_level=limit_per_level)
    records: list[dict[str, object]] = []
    for index, entry in enumerate(selected, start=1):
        details = generate(entry)
        records.append(build_record(entry, details, domain=domain, source=source))
        if on_progress:
            on_progress(index, len(selected))
    return records


# --- domain (AI / technical) corpus ------------------------------------------


@dataclass
class DomainDetails:
    """Everything Bedrock generates for a technical term (CEFR level is model-assigned)."""

    definition: str
    example: str = ""
    synonyms: list[str] = field(default_factory=list)
    cefr_level: str = "B2"
    subfield: str = ""


DOMAIN_SYSTEM_PROMPT = (
    "You write concise technical dictionary entries for an English vocabulary tutor. "
    "Always reply with a single JSON object and nothing else."
)


def domain_details_prompt(term: str, domain: str) -> str:
    """Prompt for a technical term: prose, synonyms, CEFR level, and subfield."""
    return (
        f'Write a learner dictionary entry for the {domain} term "{term}".\n\n'
        "Return JSON with exactly these keys:\n"
        '  "definition": one clear sentence in plain English,\n'
        '  "example": one natural usage sentence,\n'
        '  "synonyms": array of up to 3 related terms (may be empty),\n'
        f'  "cefr_level": the CEFR level a learner needs to understand this {domain} term '
        '(one of "B1", "B2", "C1", "C2"),\n'
        '  "subfield": a short topic label such as "llm_architecture", "machine_learning", '
        '"systems", or "evaluation".\n'
        "Do not add any other keys or text."
    )


def parse_domain_details(raw: str) -> DomainDetails:
    """Parse Bedrock's JSON reply, defaulting the CEFR level if it is missing or invalid."""
    base = parse_details(raw)  # reuse the tolerant JSON extraction
    text = raw.strip()
    fence = re.search(r"```(?:json)?\s*(.*?)```", text, flags=re.DOTALL)
    if fence:
        text = fence.group(1).strip()
    start, end = text.find("{"), text.rfind("}")
    payload: dict[str, object] = {}
    if start != -1 and end != -1:
        try:
            payload = json.loads(text[start : end + 1])
        except json.JSONDecodeError:
            payload = {}

    level = str(payload.get("cefr_level", "B2")).strip().upper()
    try:
        level = CefrLevel(level).value
    except ValueError:
        level = CefrLevel.B2.value

    return DomainDetails(
        definition=base.definition,
        example=base.example,
        synonyms=base.synonyms,
        cefr_level=level,
        subfield=slugify(str(payload.get("subfield", ""))),
    )


def generate_domain_details(
    term: str, domain: str = "ai", bedrock: BedrockClient | None = None
) -> DomainDetails:
    """Call Bedrock for a technical term's entry."""
    client = bedrock or BedrockClient()
    reply = client.generate(domain_details_prompt(term, domain), system=DOMAIN_SYSTEM_PROMPT)
    return parse_domain_details(reply)


def parse_term_list(text: str) -> list[str]:
    """Parse a plain-text term list: one term per line, `#` comments, `term,pos` tolerated."""
    terms: list[str] = []
    seen: set[str] = set()
    for line in text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        term = stripped.split(",")[0].strip()
        if term and term.lower() not in seen:
            seen.add(term.lower())
            terms.append(term)
    return terms


def build_domain_corpus(
    terms: Iterable[str],
    generate: Callable[[str], DomainDetails],
    *,
    domain: str = "ai",
    source: str = "bedrock-generated",
    on_progress: Callable[[int, int], None] | None = None,
) -> list[dict[str, object]]:
    """Enrich a domain term list into records (CEFR level assigned by the model)."""
    ordered = list(terms)
    records: list[dict[str, object]] = []
    for index, term in enumerate(ordered, start=1):
        details = generate(term)
        entry = CefrEntry(
            headword=term,
            pos="",
            cefr_level=details.cefr_level,
            topic=details.subfield,
        )
        record = build_record(
            entry,
            TermDetails(details.definition, details.example, details.synonyms),
            domain=domain,
            id_prefix=domain,
            source=source,
        )
        if details.subfield:
            record["subfield"] = details.subfield
        records.append(record)
        if on_progress:
            on_progress(index, len(ordered))
    return records


def write_jsonl(records: Sequence[dict[str, object]], path: str) -> int:
    """Write records as JSON Lines. Returns the number written."""
    with open(path, "w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")
    return len(records)
